#!/bin/bash

echo "____________________________________________________________________________________________________________________________________"
echo "                              PyTest"
echo "____________________________________________________________________________________________________________________________________"
# Teste unitários, integração e cobertura de código
docker exec $1 pytest --disable-warnings --cov=./$2/src ./$2/py_test --cov-report html

echo "____________________________________________________________________________________________________________________________________"
echo "                              MyPy"
echo "____________________________________________________________________________________________________________________________________"
# Type hints
docker exec $1 mypy ./$2 --ignore-missing-imports --follow-imports skip

echo "____________________________________________________________________________________________________________________________________"
echo "                              Flake8"
echo "____________________________________________________________________________________________________________________________________"
# Style violations, syntax errors, and complexity
docker exec $1 flake8 --max-complexity 12 ./$2

echo "____________________________________________________________________________________________________________________________________"
echo "                              Restart Docker Container and Run Streamlit"
echo "____________________________________________________________________________________________________________________________________"
docker restart $1
docker exec $1 streamlit run ./$2/main.py --server.port=8080 --server.address=0.0.0.0